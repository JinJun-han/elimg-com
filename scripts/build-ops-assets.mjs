import { readFile, writeFile } from 'node:fs/promises';
const root = new URL('../', import.meta.url);
const paths = { '/ops/index.html': ['ops/index.html', 'text/html; charset=utf-8'], '/ops/ops.css': ['ops/ops.css', 'text/css; charset=utf-8'], '/ops/ops.js': ['ops/ops.js', 'text/javascript; charset=utf-8'] };
const assets = {};
for (const [route, [file, type]] of Object.entries(paths)) assets[route] = { type, body: await readFile(new URL(file, root), 'utf8') };
const output = '// Generated by scripts/build-ops-assets.mjs. Private assets must not enter the public asset bundle.\nexport const privateAssets = ' + JSON.stringify(assets) + ';\n';
const target = new URL('server/ops-assets.mjs', root);
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8').catch(() => '') !== output) throw new Error('Run node scripts/build-ops-assets.mjs before committing.');
  console.log('Private asset bundle matches source.');
} else { await writeFile(target, output); console.log('Private asset bundle generated.'); }
